def json_text(value):
    return json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True) + "\n"


def code(analysis, start, end):
    """Explicit padding and fixed PC offsets also support halfword-aligned entries."""
    nodes = analysis.nodes(start, end)
    functions = [f for f in analysis.functions if start <= f.address and f.end <= end]
    entries = {function.address: function for function in functions}
    ends = {f.end: f.name for f in functions}
    closed, fixed_literals = set(), []
    lines = ['.include "macro.inc"', '.section .text, "ax", %progbits',
             f"@ Generated by gba_split; ROM [0x{start:08X}, 0x{end:08X})", ""]
    # GAS can pad an entire input section to its maximum alignment. Do not give a
    # 2-mod-4 span word alignment; the fixed-address linker supplies its ROM VMA.
    if start % 4 == 0 and (end - start) % 4 == 0:
        lines += [".balign 4, 0", ""]

    def close(address):
        if address in ends and address not in closed:
            lines.extend([f".size {ends[address]}, . - {ends[address]}", ""])
            closed.add(address)

    for node in nodes:
        close(node.address)
        if node.kind == "entry":
            lines.extend(["", node.text])
        elif node.kind == "label":
            if analysis.symbols[node.name].isa is None and node.name in analysis.exported_labels:
                lines.append(".global " + node.name)
            lines.append(node.text + f" @ 0x{node.address:08X}")
            if node.address in entries and node.name == entries[node.address].name:
                for alias in dict.fromkeys(analysis.symbol_aliases.get(node.address, [])):
                    lines += [".global " + alias, ".type " + alias + ", %function",
                              (".thumb_set " if node.isa == "thumb" else ".set ") + alias + ", " + node.name,
                              f".size {alias}, 0x{entries[node.address].size:X}"]
        elif node.kind == "padding":
            if node.size:
                raw = analysis.config.rom[node.address - analysis.config.base:node.end - analysis.config.base]
                lines.append("    .byte " + ", ".join(f"0x{b:02X}" for b in raw) + " @ alignment padding")
        else:
            text = analysis.data_text(node) if node.kind == "data" else node.text
            literal = literal_load(node, analysis.config.rom, analysis.config.base) if node.kind == "instruction" else None
            if literal:
                target, replacement = literal
                require(target in analysis.symbols, "Undefined literal label: " + target)
                target_address = analysis.symbols[target].address
                # GAS cannot relocate a Thumb PC8 load to a different object. Its
                # section-relative PC rounding also differs for a 2-mod-4 VMA.
                if not start <= target_address < end or start % 4:
                    comment = text.split("@", 1)[1].strip() if "@" in text else ""
                    text = replacement + " @ " + target + ("; " + comment if comment else "")
                    fixed_literals.append(node.address)
            lines.append("    " + text)
    close(end)
    require(len(closed) == len(functions), "Incomplete entry size markers")
    return "\n".join(lines) + "\n", fixed_literals


def decoded_resource(analysis, segment):
    if segment.key not in analysis.decoded_resources:
        raw = analysis.config.rom[segment.start:segment.start + segment.size]
        metadata = {"format": segment.kind}
        compression = segment.options.get("compress")
        decoded = raw
        if compression:
            from .graphics import decompress_huffman, decompress_lz, decompress_rle
            decompress = {"lz": decompress_lz, "rle": decompress_rle, "huffman": decompress_huffman}[compression]
            try:
                decoded, consumed = decompress(raw)
            except ValueError as error:
                raise ValueError(segment.key + ": " + str(error)) from None
            metadata.update(compression=compression, compressed_size=consumed,
                            decompressed_size=len(decoded), trailing_bytes=len(raw) - consumed)
        analysis.decoded_resources[segment.key] = decoded, metadata
    decoded, metadata = analysis.decoded_resources[segment.key]
    return decoded, dict(metadata)


def tilemap_options(segment):
    kind = segment.options.get("format", "text")
    return {"width": segment.options.get("width", 32),
            "layout": segment.options.get("layout", "linear" if kind == "affine" else "screenblocks"),
            "format": kind}


def resource_palette(analysis, segment, mapped=False):
    palette = segment.options.get("palette")
    if type(palette) is int:
        colors = 256 if segment.kind == "8bpp" or mapped else 16
        offset = palette - analysis.config.base if palette >= analysis.config.base else palette
        require(0 <= offset <= len(analysis.config.rom) - colors * 2, "Palette is outside ROM: " + segment.key)
        palette = analysis.config.rom[offset:offset + colors * 2]
    elif isinstance(palette, str):
        palette = contained_path(analysis.config.root, palette).read_bytes()
    return palette


def resource_assets(analysis, segment):
    decoded, metadata = decoded_resource(analysis, segment)
    stem = "assets/" + segment.key
    compression = segment.options.get("compress")
    asset = stem + "." + (compression or segment.kind)
    exported = {}
    if compression:
        exported[stem + "." + segment.kind] = decoded
    if segment.kind in {"4bpp", "8bpp", "tilemap"}:
        from .graphics import decode_tilemap, export_4bpp, export_8bpp, export_tilemap
        try:
            if segment.kind == "tilemap":
                options = tilemap_options(segment)
                entries, width, height = decode_tilemap(decoded, **options)
                exported[stem + ".json"] = json_text(dict(options, width=width, height=height,
                                                         entry_order="row-major", entries=entries))
                metadata.update(options, height=height, entries=len(entries))
            else:
                width = segment.options.get("width", 128)
                map_name = segment.options.get("tilemap")
                palette = resource_palette(analysis, segment, mapped=bool(map_name))
                tile_palette = palette
                if segment.kind == "4bpp" and palette is not None:
                    if isinstance(palette, bytes) and len(palette) == 512:
                        tile_palette = palette[:32]
                    elif isinstance(palette, list) and len(palette) == 256:
                        tile_palette = palette[:16]
                exporter = export_4bpp if segment.kind == "4bpp" else export_8bpp
                exported[stem + ".png"] = exporter(decoded, width, tile_palette)
                metadata.update(width=width, tiles=len(decoded) // (32 if segment.kind == "4bpp" else 64))
                if map_name:
                    target_map = next(s for s in analysis.config.segments
                                      if s.namespace == segment.namespace and s.name == map_name)
                    map_data, _ = decoded_resource(analysis, target_map)
                    preview = stem + ".map.png"
                    exported[preview] = export_tilemap(decoded, map_data, **tilemap_options(target_map),
                                                      palette=palette, bpp=4 if segment.kind == "4bpp" else 8)
                    metadata.update(tilemap=map_name, map_preview=preview)
        except ValueError as error:
            raise ValueError(segment.key + ": " + str(error)) from None
    return asset, exported, metadata


def module_rodata(analysis, segment):
    """Emit actual object labels for C-owned data, without offset aliases."""
    symbols = sorted((symbol for symbol in analysis.address_symbols.by_name.values()
                      if symbol.kind != "func" and segment.address <= symbol.address < segment.end),
                     key=lambda symbol: symbol.address)
    require(symbols and symbols[0].address == segment.address,
            "Module rodata needs a named object at its start: " + segment.name)
    require(len({symbol.address for symbol in symbols}) == len(symbols),
            "Module rodata objects must have distinct addresses: " + segment.name)
    lines = ['.include "macro.inc"', f'.section {segment.rodata_section}, "a", %progbits',
             f"@ Generated by gba_split; ROM [0x{segment.address:08X}, 0x{segment.end:08X})"]
    functions = {symbol.value: name for name, symbol in reversed(list(analysis.symbols.items()))
                 if symbol.isa is not None}
    for index, symbol in enumerate(symbols):
        end = symbols[index + 1].address if index + 1 < len(symbols) else segment.end
        size = symbol.size if symbol.size is not None else end - symbol.address
        require(symbol.address + size <= end, "Overlapping rodata object: " + symbol.name)
        lines += ["", ".global " + symbol.name, ".type " + symbol.name + ", %object",
                  symbol.name + f": @ 0x{symbol.address:08X}"]
        raw = analysis.config.rom[symbol.address - analysis.config.base:end - analysis.config.base]
        words_end = len(raw) - len(raw) % 4
        for offset in range(0, words_end, 4):
            value = struct.unpack_from("<I", raw, offset)[0]
            expression = (functions.get(value) or analysis.address_symbols.reference(value)
                          or analysis.pointer_names.get(value))
            if expression is not None:
                analysis.reference_symbol(re.match(IDENTIFIER, expression)[0], segment.rodata_owner)
            else:
                expression = f"0x{value:08X}"
            lines.append(f"    .4byte {expression} @ 0x{value:08X}")
        if words_end < len(raw):
            lines.append("    .byte " + ", ".join(f"0x{value:02X}" for value in raw[words_end:]))
        lines.append(f".size {symbol.name}, 0x{size:X}")
    return "\n".join(lines) + "\n", None, symbols[0].name, {}, {}


def data(analysis, segment):
    if getattr(segment, "rodata_owner", None) is not None:
        return module_rodata(analysis, segment)
    anchor = f"_gba_data_{segment.address:08X}"
    require(anchor not in analysis.symbols, "Generated data anchor conflicts with a CFG symbol: " + anchor)
    section = getattr(segment, "rodata_section", None) or ".rodata"
    lines = ['.include "macro.inc"', f'.section {section}, "a", %progbits',
             f"@ Generated by gba_split; ROM [0x{segment.address:08X}, 0x{segment.end:08X})",
             ".global " + anchor, f".type {anchor}, %object", anchor + ":"]
    raw = analysis.config.rom[segment.start:segment.start + segment.size]
    exported, metadata = {}, {}
    if segment.kind == "rodata" and not segment.options.get("compress"):
        by_value = {symbol.value: name for name, symbol in reversed(list(analysis.symbols.items()))
                    if symbol.isa is not None}
        words_end = len(raw) - len(raw) % 4
        for offset in range(0, words_end, 4):
            value = struct.unpack_from("<I", raw, offset)[0]
            expression = by_value.get(value)
            if expression is None:
                expression = analysis.address_expression(value) or f"0x{value:08X}"
            lines.append(f"    .4byte {expression} @ 0x{value:08X}")
        if words_end < len(raw):
            lines.append("    .byte " + ", ".join(f"0x{value:02X}" for value in raw[words_end:]))
        asset = None
    elif segment.kind == "sound":
        resource = analysis.resource_exports[segment.key]
        lines.append(resource["body"])
        exported.update(resource["files"])
        metadata = resource["metadata"]
        asset = None
    else:
        asset, exported, metadata = resource_assets(analysis, segment)
        lines.append(f'    .incbin "{asset}"')
    sound_symbols = analysis.resource_exports.get(segment.key, {}).get("symbols", {})
    for symbol in analysis.address_symbols.by_name.values():
        if (symbol.kind != "func" and segment.address <= symbol.address < segment.end
                and symbol.name != anchor and symbol.name not in sound_symbols):
            lines += [".global " + symbol.name, ".type " + symbol.name + ", %object",
                      f".set {symbol.name}, {anchor} + 0x{symbol.address - segment.address:X}"]
            if symbol.size is not None:
                lines.append(f".size {symbol.name}, 0x{symbol.size:X}")
    lines.append(f".size {anchor}, . - {anchor}")
    return "\n".join(lines) + "\n", asset, anchor, exported, metadata


def linker_sections(rows):
    """Use the same split .text/.rodata layout for production and verification."""
    separate_rodata = {row["object"] for row in rows if row.get("rodata_owner")}
    lines = []
    for row in rows:
        section, address, obj = row["section"], row["address"], row["object"]
        if row.get("rodata_owner"):
            inputs = row["rodata_section"]
        elif obj in separate_rodata:
            inputs = ".text .text.* .data .data.*"
        else:
            inputs = ".text .text.* .rodata .rodata.* .data .data.*"
        lines.append(f'  {section} 0x{address:08X} (READONLY) : SUBALIGN({row["subalign"]}) {{ "{obj}"({inputs}) }}')
        if obj in separate_rodata:
            kind = "rodata" if row.get("rodata_owner") else "text"
            lines.append(f'  ASSERT(SIZEOF({section}) == 0x{row["size"]:X}, "{row["name"]} {kind} size mismatch")')
    return lines


def linker(rows, entry, functions=None, addresses=None):
    lines = ['OUTPUT_FORMAT("elf32-littlearm")', "OUTPUT_ARCH(arm)", f"ENTRY({entry})"]
    if functions or addresses:
        lines.append("/* Fixed addresses for references not supplied by linked objects. */")
        lines.extend(undefined_text(functions or {}).splitlines())
        lines.extend(undefined_text(addresses or {}, provide=True).splitlines())
    lines.extend(["SECTIONS", "{"])
    lines.extend(linker_sections(rows))
    lines.extend(["  /DISCARD/ : { *(*) }", "}"])
    return "\n".join(lines) + "\n"


def c_source(analysis, segment):
    directory = analysis.config.output.relative_to(analysis.config.root).as_posix()
    lines = ['#include "include_asm.h"', ""]
    for function in analysis.functions:
        if function.module == segment.name:
            lines += [f'INCLUDE_ASM("{directory}/nonmatchings/{segment.name}", {function.name});', ""]
    return "\n".join(lines)


def undefined_text(symbols, *, provide=False):
    definitions = (f"{name} = 0x{address:08X}"
                   for name, address in sorted(symbols.items(), key=lambda item: (item[1], item[0])))
    return "".join((f"PROVIDE({definition});\n" if provide else f"{definition};\n")
                   for definition in definitions)


def write_if_changed(path, text, create_only=False):
    if path.exists():
        if create_only or path.read_text(encoding="utf-8") == text:
            return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def c_renames(analysis, previous):
    old_units = {(row["address"], row["size"]): row
                 for row in previous.get("chunks", []) if row["type"] == "c"}
    result = {}
    for segment in analysis.config.segments:
        old = old_units.get((segment.address, segment.size))
        if segment.kind == "c" and old is not None and old["name"] != segment.name:
            result[segment.name] = old["name"]
    return result


def function_renames(analysis, previous):
    current = {(function.address, function.size, function.isa): function for function in analysis.functions}
    names = {}
    for old in previous.get("functions", []):
        function = current.get((old["address"], old["size"], old["isa"]))
        if function is None:
            continue
        aliases = analysis.symbol_aliases.get(function.address, [])
        for name in [old["name"], *old.get("aliases", [])]:
            if name != function.name and name not in aliases:
                names[name] = function.name
    return names


def renamed_c_text(text, names):
    """Replace known function identifiers, preserving comments and C literals."""
    return C_TOKENS.sub(lambda match: names.get(match[0], match[0]), text)


def rewrite_asm_includes(text, folders, directory_renames=None):
    """Update generated includes, including inactive fallbacks, not comments."""
    changes = []
    for token in C_TOKENS.finditer(text):
        if token[0] not in {"INCLUDE_ASM", "INCLUDE_RODATA"}:
            continue
        call = re.match(r'\s*\(\s*"([^"]+)"\s*,\s*(' + IDENTIFIER + r')\s*\)', text[token.end():])
        if call is None:
            continue
        if not re.search(r"(?:^|/)(?:nonmatchings|matchings)/", call[1] + "/"):
            continue
        folder = folders.get(call[2], (directory_renames or {}).get(call[1]))
        if folder is None:
            continue
        start, end = call.span(1)
        changes.append((token.end() + start, token.end() + end, folder))
    for start, end, folder in reversed(changes):
        text = text[:start] + folder + text[end:]
    return text


def source_files(root):
    return {path.relative_to(root).as_posix(): path.read_text(encoding="utf-8")
            for directory in (root / "src", root / "include")
            for path in directory.rglob("*")
            if path.is_file() and path.suffix in {".c", ".h", ".s", ".inc"}}


def asm_references(text):
    """Find INCLUDE_ASM references in source, including inactive branches.

    Like splat's CommonSegC, this scans source without running a preprocessor
    or a compiler. Comments and string literals are not macro invocations.
    """
    text = C_TOKENS.sub(lambda match: " " if match[0].startswith(("//", "/*")) else match[0], text)
    names = set()
    for token in C_TOKENS.finditer(text):
        if token[0] != "INCLUDE_ASM":
            continue
        call = re.match(r'\s*\(\s*"(?:\\.|[^"\\])*"\s*,\s*(' + IDENTIFIER + r')\s*\)', text[token.end():])
        if call:
            names.add(call[1])
    return names


def classify_sources(analysis, sources):
    """Classify reference paths by source references, never by linked bytes."""
    references = {segment.name: asm_references(sources["src/" + segment.name + ".c"])
                  for segment in analysis.config.segments
                  if segment.kind in CODE and "src/" + segment.name + ".c" in sources}
    statuses = {}
    for function in analysis.functions:
        names = {function.name, *analysis.symbol_aliases.get(function.address, ())}
        statuses[function.name] = ("matching" if function.module in references
                                  and not names & references[function.module] else "assembly")
    return statuses


def classification_counts(analysis, functions):
    """Count game C entries; library and assembly-only units are not progress."""
    modules = {segment.name for segment in analysis.config.segments
               if segment.kind == "c" and not segment.name.startswith("sdk/")}
    entries = [row for row in functions if row["module"] in modules]
    matchings = sum(row["matching"] for row in entries)
    return dict(matchings=matchings, nonmatchings=len(entries) - matchings, total=len(entries),
                scope="game_c_modules", method="splat_include_asm_references")


def make_units(config):
    code_names = [segment.name for segment in config.segments if segment.kind in CODE]
    data_names = [segment.unit for segment in config.segments
                  if segment.kind not in CODE and segment.rodata_owner is None]
    return ("# Generated by gba_split.\n"
            + "ROM_NAME := " + config.name + "\n"
            + "BASEROM := " + config.target.relative_to(config.root).as_posix() + "\n"
            + "CODE_UNITS := " + " ".join(code_names) + "\n"
            + "DATA_UNITS := " + " ".join(data_names) + "\n")


def generated_layout(path, root, actual):
    """Recover the old layout from generated assembly when no report exists."""
    require("units.mk" in actual and (path / "units.mk").read_text().startswith("# Generated by gba_split."),
            "Output has no generated module list; choose an empty output directory")
    chunks, functions = [], []
    header = re.compile(r"^@ Generated by gba_split; ROM \[(0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+)\)", re.M)
    entry = re.compile(r"^(non_word_aligned_thumb_func_start|thumb_func_start|arm_func_start)\s+("
                       + IDENTIFIER + r")\s*\n\2:\s*@\s*(0x[0-9A-Fa-f]+)", re.M)
    for name in sorted(actual):
        relative = Path(name)
        if name in {"macro.inc", "linker.ld", "units.mk"}:
            continue
        if relative.parts[0] == "assets" and len(relative.parts) > 2 and relative.parts[1] in {"gfx", "sound"}:
            continue
        require(relative.parts[0] in {"obj", "data", "matchings", "nonmatchings"}
                and relative.suffix == ".s", "Unrecognized file in generated output: " + name)
        text = (path / name).read_text(encoding="utf-8")
        span = header.search(text)
        require(span is not None or relative.parts[0] in {"matchings", "nonmatchings"}
                and text.startswith("@ Alias of "), "Unrecognized generated assembly: " + name)
        if relative.parts[0] != "obj":
            continue
        start, end = (int(value, 16) for value in span.groups())
        module = relative.relative_to("obj").with_suffix("").as_posix()
        chunks.append(dict(address=start, size=end - start, name=module,
                           type="c" if (root / "src" / (module + ".c")).is_file() else "asm"))
        entries = list(entry.finditer(text))
        aliases = re.findall(r"^\.(?:thumb_set|set)\s+(" + IDENTIFIER + r"),\s*(" + IDENTIFIER + r")\s*$", text, re.M)
        for index, marker in enumerate(entries):
            address = int(marker[3], 16)
            finish = int(entries[index + 1][3], 16) if index + 1 < len(entries) else end
            functions.append(dict(address=address, size=finish - address, name=marker[2], module=module,
                                  isa="arm" if marker[1] == "arm_func_start" else "thumb",
                                  aliases=[alias for alias, target in aliases if target == marker[2]]))
    require(chunks, "Output has no generated code modules; choose an empty output directory")
    return dict(schema=SCHEMA, chunks=chunks, functions=functions,
                generated_files={name: digest((path / name).read_bytes()) for name in sorted(actual)})


def check_generated(path, root=None):
    """Check output ownership; an optional report also checks stored hashes."""
    require(path.is_dir() and not path.is_symlink(), "Assembly output is not a regular directory")
    manifest_path = path / "manifest.json"
    actual = set()
    for item in path.rglob("*"):
        require(not item.is_symlink(), "Symlink in generated output: " + str(item))
        if item.is_file():
            actual.add(item.relative_to(path).as_posix())
    if not manifest_path.exists():
        return generated_layout(path, root or path.parent, actual)
    require(manifest_path.is_file(), "Split report is not a regular file")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    require(isinstance(manifest, dict) and manifest.get("schema") in {"gba.split.v1", SCHEMA}, "Unrecognized split manifest")
    files = manifest.get("generated_files")
    require(isinstance(files, dict) and files, "Missing generated file inventory")
    require(actual == set(files) | {"manifest.json"},
            "Output contains missing or additional files; choose a fresh build/ output")
    for name, fingerprint in files.items():
        require(isinstance(name, str) and not Path(name).is_absolute() and ".." not in Path(name).parts,
                "Invalid generated file path")
        require((path / name).resolve().is_relative_to(path.resolve()), "Generated file escapes output")
        require(isinstance(fingerprint, str) and re.fullmatch(r"[0-9a-f]{64}", fingerprint),
                "Invalid generated file fingerprint")
        require(digest((path / name).read_bytes()) == fingerprint,
                "Generated file was edited: " + name + "; choose a fresh build/ output")
    return manifest


def generate(analysis):
    """Prepare original-ROM references and layout without compiling or writing."""
    config = analysis.config
    destination = config.output
    manifest = dict(schema=SCHEMA, config=config.path.relative_to(config.root).as_posix(),
                    project_root=os.path.relpath(config.root, destination),
                    rom=dict(size=len(config.rom), base=config.base, code_end=config.code_end,
                             sha1=hashlib.sha1(config.rom).hexdigest(), sha256=digest(config.rom)),
                    inputs=config.fingerprints, chunks=[], functions=[], data=[], generated_files={},
                    diagnostics=dict(instructions=dict(analysis.counts),
                                     disassembly_sha256=analysis.disassembly_hash,
                                     native_function_hints=sum(h.command.endswith("_func") for h in analysis.hints),
                                     entry_markers=len(analysis.functions),
                                     suppressed_function_hints=analysis.suppressed_hints,
                                     boundary="next_entry_or_module",
                                     note="Marked spans include pools/padding and may be alternate or shared entries."))
    outputs = {}

    def save(name, content):
        require(name not in outputs, "Generated path collision: " + name)
        require(not Path(name).is_absolute() and ".." not in Path(name).parts,
                "Generated path escapes output: " + name)
        raw = content.encode("utf-8") if isinstance(content, str) else content
        outputs[name] = raw
        manifest["generated_files"][name] = digest(raw)

    # Build and validate the complete result in memory before writing any file.
    rodata = {segment.rodata_owner: segment for segment in config.segments
              if segment.rodata_owner is not None}
    rodata_sources = {}
    for segment in config.segments:
        row = dict(offset=segment.start, address=segment.address, size=segment.size,
                   type=segment.kind, name=segment.name,
                   namespace=segment.namespace, object=segment.object, subalign=segment.subalign,
                   section=segment.section, source=segment.source,
                   sha256=digest(config.rom[segment.start:segment.start + segment.size]))
        if segment.rodata_owner is not None:
            row["rodata_owner"] = segment.rodata_owner
            row["rodata_section"] = segment.rodata_section
        if segment.kind in CODE:
            text, fixed = code(analysis, segment.address, segment.end)
            if segment.name in rodata:
                text += '\n.include "' + rodata[segment.name].source + '"\n'
            row["fixed_literal_loads"] = fixed
            row["entries"] = sum(f.module == segment.name for f in analysis.functions)
        else:
            text, asset, anchor, exported, metadata = data(analysis, segment)
            row["anchor"] = anchor
            if metadata:
                row["resource"] = metadata
            for name, content in exported.items():
                save(name, content)
            if asset:
                save(asset, config.rom[segment.start:segment.start + segment.size])
                row["asset"] = asset
            manifest["data"].append(row)
        if segment.rodata_owner is not None:
            rodata_sources.setdefault(segment.source, []).append(text)
        else:
            save(segment.source, text)
        manifest["chunks"].append(row)
    for source, texts in rodata_sources.items():
        save(source, "\n".join(texts))
    for function in analysis.functions:
        text, fixed = code(analysis, function.address, function.end)
        row = asdict(function)
        row.update(offset=function.address - config.base, type="function",
                   source=function.source, boundary="next_entry_or_module", fixed_literal_loads=fixed,
                   aliases=list(dict.fromkeys(analysis.symbol_aliases.get(function.address, []))),
                   sha256=digest(config.rom[function.address - config.base:function.end - config.base]))
        save(function.source, text)
        for alias in dict.fromkeys(analysis.symbol_aliases.get(function.address, [])):
            alias_path = f"nonmatchings/{function.module}/{alias}.s"
            if alias_path != function.source:
                save(alias_path, f'@ Alias of {function.name}; keeps existing INCLUDE_ASM source paths valid.\n'
                                 f'.include "{function.source}"\n')
        manifest["functions"].append(row)
    save("macro.inc", Path(__file__).with_name("macro.inc").read_text(encoding="utf-8"))
    manifest["linker_symbols"] = dict(functions=dict(analysis.undefined_funcs), data=dict(analysis.undefined_syms))
    save("linker.ld", linker(manifest["chunks"], analysis.functions[0].name,
                            analysis.undefined_funcs, analysis.undefined_syms))
    save("units.mk", make_units(config))
    return manifest, outputs


def split(analysis):
    config = analysis.config
    destination = config.output
    previous_manifest = {}
    if destination.exists():
        require(destination.is_dir() and not destination.is_symlink(), "Output is not a regular directory")
        if any(destination.iterdir()):
            previous_manifest = check_generated(destination, config.root)
    previous = previous_manifest.get("generated_files", {})
    renames = c_renames(analysis, previous_manifest)
    originals = source_files(config.root)
    names = function_renames(analysis, previous_manifest)
    sources = {name: renamed_c_text(text, names) if Path(name).suffix in {".c", ".h"} else text
               for name, text in originals.items()}
    assembly_path = destination.relative_to(config.root).as_posix()
    directory_renames = {f"{assembly_path}/{folder}/{old}": f"{assembly_path}/{folder}/{new}"
                         for new, old in renames.items() for folder in ("nonmatchings", "matchings")}
    moved_sources = set()
    for new_name, old_name in renames.items():
        old_path, new_path = "src/" + old_name + ".c", "src/" + new_name + ".c"
        if old_path in sources and new_path not in sources:
            sources[new_path] = rewrite_asm_includes(sources.pop(old_path), {}, directory_renames)
            moved_sources.add(old_path)
    manifest, outputs = generate(analysis)
    if renames:
        manifest["unit_renames"] = renames
    statuses = classify_sources(analysis, sources)
    folders = {}
    for function, row in zip(analysis.functions, manifest["functions"]):
        matching = statuses[function.name] == "matching"
        directory = ("matchings" if matching else "nonmatchings") + "/" + function.module
        source = directory + "/" + function.name + ".s"
        row.update(source=source, matching=matching, match_status=statuses[function.name])
        if source != function.source:
            outputs[source] = outputs.pop(function.source)
        folders[function.name] = assembly_path + "/" + directory
        for alias in row["aliases"]:
            old_path = f"nonmatchings/{function.module}/{alias}.s"
            new_path = directory + "/" + alias + ".s"
            folders[alias] = folders[function.name]
            if old_path != new_path:
                outputs.pop(old_path)
                outputs[new_path] = (f"@ Alias of {function.name}; keeps existing INCLUDE_ASM source paths valid.\n"
                                     f'.include "{source}"\n').encode("utf-8")
    manifest["generated_files"] = {name: digest(raw) for name, raw in outputs.items()}
    manifest["diagnostics"]["classification"] = classification_counts(analysis, manifest["functions"])
    sources = {name: rewrite_asm_includes(text, folders) for name, text in sources.items()}

    # Never overwrite edits made while preparing the generated output.
    require(source_files(config.root) == originals, "C sources or headers changed during split; run split again")
    for name, fingerprint in config.fingerprints.items():
        require(digest((config.root / name).read_bytes()) == fingerprint,
                "Split input changed during generation: " + name + "; run split again")
    if previous_manifest:
        require(check_generated(destination, config.root) == previous_manifest, "Assembly output changed during split; run split again")
    destination.mkdir(parents=True, exist_ok=True)
    for name, raw in outputs.items():
        path = destination / name
        require(path.resolve().is_relative_to(destination.resolve()), "Generated path escapes output: " + name)
        if previous.get(name) != manifest["generated_files"][name]:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
    obsolete_dirs = set()
    for name in previous.keys() - outputs.keys():
        path = destination / name
        path.unlink()
        obsolete_dirs.update(parent for parent in path.parents if parent != destination and parent.is_relative_to(destination))
    for directory in sorted(obsolete_dirs, key=lambda path: len(path.parts), reverse=True):
        if directory.exists() and not any(directory.iterdir()):
            directory.rmdir()
    for folder in ("matchings", "nonmatchings"):
        (destination / folder).mkdir(exist_ok=True)
    for name, text in sources.items():
        write_if_changed(config.root / name, text)
    for name in moved_sources:
        (config.root / name).unlink()
    for segment in config.segments:
        if segment.kind == "c":
            write_if_changed(config.root / "src" / (segment.name + ".c"),
                             c_source(analysis, segment), create_only=True)
    write_if_changed(config.root / "include/include_asm.h",
                     Path(__file__).with_name("include_asm.h").read_text(encoding="utf-8"), create_only=True)
    write_if_changed(destination / "manifest.json", json_text(manifest))
    return manifest
