void Party_RestoreHpMp(void)
{
    u8 slot;
    u8 characterId;
    struct PartyCharacter *character;

    for (slot = 0; slot < PARTY_MEMBER_SLOT_COUNT; slot++)
    {
        characterId = gPartyMembers[slot];
        if (characterId != PARTY_NO_MEMBER)
        {
            if (characterId != 0)
                characterId--;
            character = &gPartyCharacters[characterId];
            character->hp = character->maxHp;
            character->mp = character->maxMp;
        }
    }
}

void Party_SetEquipment(u8 characterId, u8 itemId, u8 slot)
{
    u8 index = characterId;
    u8 oldItem;
    u8 *equipment;
    struct PartyCharacter *character;

    if (index != 0)
        index--;
    character = &gPartyCharacters[index];
    switch (slot)
    {
    case 1:
        equipment = &character->equipSlot2;
        break;
    case 2:
        equipment = &character->equipSlot3;
        break;
    case 3:
        equipment = &character->equipSlot4;
        break;
    case 4:
        equipment = &character->equipSlot5;
        break;
    case 5:
        equipment = &character->equipSlot6;
        break;
    default:
        equipment = &character->equipSlot1;
        break;
    }
    oldItem = *equipment;
    *equipment = itemId;
    if (oldItem != PARTY_NO_ITEM && gPartyItemCounts[oldItem] < PARTY_MAX_ITEM_COUNT)
        Party_AddItem(oldItem, 1);
    Party_CalculateEquipmentBonuses(characterId);
    Party_ApplyEquipmentBonuses(characterId);
}

void Party_AddItem(u8 itemId, u8 amount)
{
    s32 count = gPartyItemCounts[itemId] + amount;

    if (count > PARTY_MAX_ITEM_COUNT)
        gPartyItemCounts[itemId] = PARTY_MAX_ITEM_COUNT;
    else
        gPartyItemCounts[itemId] = count;
}

void Party_RemoveItem(u8 itemId, u8 amount)
{
    s32 count = gPartyItemCounts[itemId] - amount;

    if (count < 0)
        count = 0;
    gPartyItemCounts[itemId] = count;
}

void Party_AddGold(u32 amount)
{
    gPartyGold += amount;
    if (gPartyGold > PARTY_MAX_GOLD)
        gPartyGold = PARTY_MAX_GOLD;
}

void Party_RemoveGold(u32 amount)
{
    gPartyGold -= amount;
    if (gPartyGold > PARTY_MAX_GOLD)
        gPartyGold = 0;
}

u8 Party_GetItemEquipmentType(u8 itemId)
{
    const u8 *items = (const u8 *)gPartyItemTable;
    s32 offset = itemId * sizeof(struct PartyItemInfo)
        + offsetof(struct PartyItemInfo, equipmentTypeAndSet);

    return items[offset] & 0xF;
}

u16 Party_GetItemBuyPriceUnits(u8 itemId)
{
    const u8 *items = (const u8 *)gPartyItemTable;
    s32 offset = itemId * sizeof(struct PartyItemInfo)
        + offsetof(struct PartyItemInfo, buyPriceUnits);
    u16 price = items[offset];

    offset++;
    return price | (items[offset] << 8);
}

u16 Party_GetItemSellPriceUnits(u8 itemId)
{
    const u8 *items = (const u8 *)gPartyItemTable;
    s32 offset = itemId * sizeof(struct PartyItemInfo);
    s32 priceOffset = offset + offsetof(struct PartyItemInfo, sellPriceUnits);
    u16 price = items[priceOffset];

    offset += offsetof(struct PartyItemInfo, sellPriceUnits) + 1;
    return price | (items[offset] << 8);
}

u8 Party_HasPrimaryEquipment(void)
{
    u16 slot;
    u8 characterId;

    for (slot = 0; slot < PARTY_MAX_MEMBERS; slot++)
    {
        characterId = gPartyMembers[slot];
        if (characterId != PARTY_NO_MEMBER)
        {
            if (characterId != 0)
                characterId--;
            if (gPartyCharacters[characterId].equipSlot1 != PARTY_NO_ITEM)
                return 1;
        }
    }
    return 0;
}

void Party_RefreshFirstCharacterSkills(u8 characterId)
{
    if (characterId <= 1)
    {
        struct PartyCharacter *character = &gPartyCharacters[0];

        Party_BuildLearnedSkills(character->skills, character->level, characterId);
        if (character->tacticsAction == 1 && (u8)(character->tacticsActionId - 5) <= 3)
        {
            character->tacticsAction = 0;
            character->tacticsActionId = 0;
        }
    }
}

