u16 Party_GetBaseStat(u8 characterId, u8 level, u8 statId)
{
    if (statId > PARTY_STAT_NOA)
    {
        switch (characterId)
        {
        case 0:
            return 10;
        case 1:
            return 10;
        case 2:
            return 10;
        case 3:
            return 10;
        case 4:
            return 10;
        case 5:
            return 10;
        case 6:
            return 10;
        case 7:
            return 10;
        case 8:
            return 10;
        case 9:
            return 10;
        case 10:
            return 10;
        }
    }
    if (characterId > 8)
    {
        switch (statId)
        {
        case PARTY_STAT_MAX_HP:
            return 999;
        case PARTY_STAT_MAX_MP:
            if (characterId == 9)
                return 999;
            return 0;
        case PARTY_STAT_NOA:
            if (characterId == 9)
                return 1;
            return 3;
        default:
            return 255;
        }
    }
    {
        const u8 *curveIds = (const u8 *)gPartyStatGrowthCurveIds;
        s32 idOffset = characterId * sizeof(gPartyStatGrowthCurveIds[0]) + statId;
        u16 curveOffset = curveIds[idOffset] * PARTY_GROWTH_LEVEL_COUNT;
        u16 value = 0;
        u16 index = 0;

        for (; index <= level; index++)
            value += ((const u8 *)gPartyStatGrowthCurves)[curveOffset + index];
        if (value == 0 && statId == PARTY_STAT_NOA)
            value = 1;
        return value;
    }
}

void Party_BuildLearnedSkills(u8 *skills, u8 level, u8 characterId)
{
    u8 count;
    u8 index;

    level++;
    if (characterId <= 1)
        characterId = 0;
    count = 0;
    index = 0;
    {
        const u8 *groups = (const u8 *)gPartySkillTable;

        for (; index < PARTY_LEARNABLE_SKILL_COUNT; index++)
        {
            s32 groupOffset = index * sizeof(struct PartySkillInfo)
                + offsetof(struct PartySkillInfo, characterGroupBits);

            if (characterId == (groups[groupOffset] >> 4))
            {
                u8 eligible = 0;
                u8 requiredLevel = gPartySkillTable[index].requiredLevel;

                if (requiredLevel == 0xFF)
                {
                    if (gPartyMembers[0] != 1)
                        goto checkEligibility;
                    goto learnSkill;
                }
                else if (requiredLevel <= level)
                    eligible = 1;
            checkEligibility:
                if (eligible != 0)
                {
                learnSkill:
                    *skills++ = index + 1;
                    count++;
                }
            }
        }
    }
    for (; count < PARTY_SKILL_SLOT_COUNT; count++)
        *skills++ = PARTY_NO_SKILL;
}

u8 Party_GetSpecialSkill(u8 characterId)
{
    struct PartyCharacter *character;

    if (characterId != 0)
        characterId--;
    character = &gPartyCharacters[characterId];
    switch (characterId)
    {
    case 0:
        if (character->equipSlot1 == 0x15
            && (character->equipSlot5 == 0xCB || character->equipSlot6 == 0xCB))
            return 0x38;
        return 0x31;
    case 1:
        return 0x32;
    case 2:
        if (character->equipSlot5 == 0xBF || character->equipSlot6 == 0xBF)
            return 0x39;
        return 0x33;
    case 3:
        if (character->equipSlot5 == 0xBF || character->equipSlot6 == 0xBF)
            return 0x3A;
        return 0x34;
    case 4:
        if (character->equipSlot1 == 0x3B)
            return 0x3B;
        return 0x35;
    case 5:
        if (character->equipSlot1 == 0x3C)
            return 0x3C;
        return 0x36;
    default:
        return PARTY_NO_SKILL;
    }
}

void Party_InitCharacter(u8 characterId)
{
    u8 index = 0;
    struct PartyCharacter *character;

    if (characterId != 0)
        index = characterId - 1;
    character = &gPartyCharacters[index];
    if ((u8)(characterId - 9) <= 1)
    {
        u32 experience;
        u8 level;

        character->level = PARTY_MAX_INTERNAL_LEVEL;
        experience = 0;
        level = 0;
        for (; level < PARTY_MAX_INTERNAL_LEVEL; level++)
            experience += gPartyExperienceIncrements[level];
        character->experience = experience;
    }
    else
    {
        character->level = 0;
        character->experience = 0;
    }
    character->specialGauge = 0;
    character->characterSlot = 0;
    {
        const u8 *equipment = (const u8 *)gPartyInitialEquipment;
        s32 offset = index * sizeof(gPartyInitialEquipment[0]);
        s32 slotOffset;

        character->equipSlot1 = equipment[offset];
        slotOffset = offset + 1;
        character->equipSlot2 = equipment[slotOffset];
        slotOffset = offset + 2;
        character->equipSlot3 = equipment[slotOffset];
        slotOffset = offset + 3;
        character->equipSlot4 = equipment[slotOffset];
        slotOffset = offset + 4;
        character->equipSlot5 = equipment[slotOffset];
        offset += 5;
        character->equipSlot6 = equipment[offset];
    }
    {
        u8 characterLevel = character->level;
        u32 experience = 0;
        u8 level = 0;

        for (; level <= characterLevel; level++)
            experience += gPartyExperienceIncrements[level];
        character->nextLevelExperience = experience;
    }
    character->maxHp = Party_GetBaseStat(characterId, character->level, PARTY_STAT_MAX_HP);
    character->maxMp = Party_GetBaseStat(characterId, character->level, PARTY_STAT_MAX_MP);
    character->baseAtc = Party_GetBaseStat(characterId, character->level, PARTY_STAT_ATC);
    character->baseDef = Party_GetBaseStat(characterId, character->level, PARTY_STAT_DEF);
    character->baseAgl = Party_GetBaseStat(characterId, character->level, PARTY_STAT_AGL);
    character->baseMen = Party_GetBaseStat(characterId, character->level, PARTY_STAT_MEN);
    character->baseRes = Party_GetBaseStat(characterId, character->level, PARTY_STAT_RES);
    character->baseNoa = Party_GetBaseStat(characterId, character->level, PARTY_STAT_NOA);
    character->baseLuc = Party_GetBaseStat(characterId, character->level, PARTY_STAT_LUC);
    character->hp = character->maxHp;
    character->mp = character->maxMp;
    character->atc = character->baseAtc;
    character->def = character->baseDef;
    character->agl = character->baseAgl;
    character->men = character->baseMen;
    character->res = character->baseRes;
    character->noa = character->baseNoa;
    character->luc = character->baseLuc;
    Party_BuildLearnedSkills(character->skills, character->level, characterId);
    character->specialSkill = Party_GetSpecialSkill(characterId);
    character->tacticsAction = 0;
    character->tacticsActionId = 0;
}

void Party_RaiseCharacterLevel(u8 targetLevel, u8 characterId)
{
    u8 level;
    u8 index = characterId;
    struct PartyCharacter *character;

    if (index != 0)
        index--;
    character = &gPartyCharacters[index];
    if (targetLevel == 0)
        level = gPartyCharacters[0].level;
    else
        level = targetLevel - 1;
    if (level <= character->level)
        return;
    character->level = level;
    {
        u8 previousLevel = character->level - 1;
        u32 experience = 0;
        u8 index = 0;

        for (; index <= previousLevel; index++)
            experience += gPartyExperienceIncrements[index];
        character->experience = experience;
    }
    {
        u8 characterLevel = character->level;
        u32 experience = 0;
        u8 index = 0;

        for (; index <= characterLevel; index++)
            experience += gPartyExperienceIncrements[index];
        character->nextLevelExperience = experience;
    }
    character->maxHp = Party_GetBaseStat(characterId, character->level, PARTY_STAT_MAX_HP);
    character->maxMp = Party_GetBaseStat(characterId, character->level, PARTY_STAT_MAX_MP);
    character->baseAtc = Party_GetBaseStat(characterId, character->level, PARTY_STAT_ATC);
    character->baseDef = Party_GetBaseStat(characterId, character->level, PARTY_STAT_DEF);
    character->baseAgl = Party_GetBaseStat(characterId, character->level, PARTY_STAT_AGL);
    character->baseMen = Party_GetBaseStat(characterId, character->level, PARTY_STAT_MEN);
    character->baseRes = Party_GetBaseStat(characterId, character->level, PARTY_STAT_RES);
    character->baseNoa = Party_GetBaseStat(characterId, character->level, PARTY_STAT_NOA);
    character->baseLuc = Party_GetBaseStat(characterId, character->level, PARTY_STAT_LUC);
    character->hp = character->maxHp;
    character->mp = character->maxMp;
    character->atc = character->baseAtc;
    character->def = character->baseDef;
    character->agl = character->baseAgl;
    character->men = character->baseMen;
    character->res = character->baseRes;
    character->noa = character->baseNoa;
    character->luc = character->baseLuc;
    Party_BuildLearnedSkills(character->skills, character->level, characterId);
    character->specialSkill = Party_GetSpecialSkill(characterId);
    character->tacticsAction = 0;
    character->tacticsActionId = 0;
    Party_CalculateEquipmentBonuses(characterId);
    Party_ApplyEquipmentBonuses(characterId);
}

void Party_AccumulateItemBonuses(u8 itemId)
{
    const struct PartyItemInfo *item;
    u8 statId;
    u8 amount;

    if (itemId == PARTY_NO_ITEM)
        return;
    item = &gPartyItemTable[itemId];
    statId = item->bonusStatIds & 0xF;
    amount = item->bonusAmounts[0];
    switch (statId)
    {
    case PARTY_ITEM_BONUS_ATC:
        gPartyEquipmentAtcBonus += amount;
        break;
    case PARTY_ITEM_BONUS_DEF:
        gPartyEquipmentDefBonus += amount;
        break;
    case PARTY_ITEM_BONUS_AGL:
        gPartyEquipmentAglBonus += amount;
        break;
    case PARTY_ITEM_BONUS_MEN:
        gPartyEquipmentMenBonus += amount;
        break;
    case PARTY_ITEM_BONUS_RES:
        gPartyEquipmentResBonus += amount;
        break;
    case PARTY_ITEM_BONUS_NOA:
        gPartyEquipmentNoaBonus += amount;
        break;
    case PARTY_ITEM_BONUS_LUC:
        gPartyEquipmentLucBonus += amount;
        break;
    }
    statId = item->bonusStatIds >> 4;
    amount = item->bonusAmounts[1];
    switch (statId)
    {
    case PARTY_ITEM_BONUS_ATC:
        gPartyEquipmentAtcBonus += amount;
        break;
    case PARTY_ITEM_BONUS_DEF:
        gPartyEquipmentDefBonus += amount;
        break;
    case PARTY_ITEM_BONUS_AGL:
        gPartyEquipmentAglBonus += amount;
        break;
    case PARTY_ITEM_BONUS_MEN:
        gPartyEquipmentMenBonus += amount;
        break;
    case PARTY_ITEM_BONUS_RES:
        gPartyEquipmentResBonus += amount;
        break;
    case PARTY_ITEM_BONUS_NOA:
        gPartyEquipmentNoaBonus += amount;
        break;
    case PARTY_ITEM_BONUS_LUC:
        gPartyEquipmentLucBonus += amount;
        break;
    }
    if ((u8)(itemId - 0x22) <= 9 || (u8)(itemId - 0x37) <= 7)
        gPartyEquipmentNoaBonus++;
}

static inline void Party_ApplyEquipmentSetBonusInline(u8 item0, u8 item1, u8 item2, u8 item3)
{
    const struct PartyItemInfo *equipment0 = &gPartyItemTable[item0];
    const struct PartyItemInfo *equipment1 = &gPartyItemTable[item1];
    const struct PartyItemInfo *equipment2 = &gPartyItemTable[item2];
    const struct PartyItemInfo *equipment3 = &gPartyItemTable[item3];
    u8 setBits = equipment0->equipmentTypeAndSet & 0xF0;
    u8 lastSetBits;

    if (setBits != (equipment1->equipmentTypeAndSet & 0xF0))
        return;
    if (setBits != (equipment2->equipmentTypeAndSet & 0xF0))
        return;
    lastSetBits = equipment3->equipmentTypeAndSet & 0xF0;
    if (setBits != lastSetBits)
        return;

    switch (lastSetBits >> 4)
    {
    case 0xF:
        gPartyEquipmentSetAtcBonus = 34;
        gPartyEquipmentSetDefBonus = 45;
        break;
    case 0xE:
        gPartyEquipmentSetAtcBonus = 60;
        gPartyEquipmentSetDefBonus = 63;
        break;
    }
}

void Party_CalculateEquipmentBonuses(u8 characterId)
{
    struct PartyCharacter *character;

    if (characterId != 0)
        characterId--;
    character = &gPartyCharacters[characterId];

    gPartyEquipmentAtcBonus = 0;
    gPartyEquipmentDefBonus = 0;
    gPartyEquipmentAglBonus = 0;
    gPartyEquipmentMenBonus = 0;
    gPartyEquipmentResBonus = 0;
    gPartyEquipmentNoaBonus = 0;
    gPartyEquipmentLucBonus = 0;
    gPartyEquipmentSetAtcBonus = 0;
    gPartyEquipmentSetDefBonus = 0;

    Party_AccumulateItemBonuses(character->equipSlot1);
    Party_AccumulateItemBonuses(character->equipSlot2);
    Party_AccumulateItemBonuses(character->equipSlot3);
    Party_AccumulateItemBonuses(character->equipSlot4);
    Party_AccumulateItemBonuses(character->equipSlot5);
    Party_AccumulateItemBonuses(character->equipSlot6);
    Party_ApplyEquipmentSetBonusInline(character->equipSlot1, character->equipSlot2,
        character->equipSlot3, character->equipSlot4);
}

void Party_ApplyEquipmentBonuses(u8 characterId)
{
    struct PartyCharacter *character;

    if (characterId != 0)
        characterId--;
    character = &gPartyCharacters[characterId];

    character->equipAtc = gPartyEquipmentAtcBonus;
    character->equipDef = gPartyEquipmentDefBonus;
    character->equipAgl = gPartyEquipmentAglBonus;
    character->equipMen = gPartyEquipmentMenBonus;
    character->equipRes = gPartyEquipmentResBonus;
    character->equipNoa = gPartyEquipmentNoaBonus;
    character->equipLuc = gPartyEquipmentLucBonus;
    character->equipAtc += gPartyEquipmentSetAtcBonus;
    character->equipDef += gPartyEquipmentSetDefBonus;

    character->atc = character->baseAtc + character->equipAtc;
    character->def = character->baseDef + character->equipDef;
    character->agl = character->baseAgl + character->equipAgl;
    character->men = character->baseMen + character->equipMen;
    character->res = character->baseRes + character->equipRes;
    character->noa = character->baseNoa + character->equipNoa;
    character->luc = character->baseLuc + character->equipLuc;
}

u8 Party_GetLevelFromExperience(s32 experience)
{
    u8 level;

    if (experience > PARTY_MAX_EXPERIENCE)
        experience = PARTY_MAX_EXPERIENCE;
    level = 0;
    while (experience >= 0)
    {
        experience -= gPartyExperienceIncrements[level];
        level++;
    }
    return level - 1;
}

u32 Party_GetNextLevelExperience(u8 level)
{
    u32 experience = 0;
    u8 index = 0;

    for (; index <= level; index++)
        experience += gPartyExperienceIncrements[index];
    return experience;
}

u8 Party_FindSkillLearnedAtLevel(u8 level, u8 characterId)
{
    u8 index;
    level++;
    if (characterId <= 1)
        characterId = 0;
    index = 0;
    {
        const u8 *groups = (const u8 *)gPartySkillTable;

        for (; index < PARTY_LEARNABLE_SKILL_COUNT; index++)
        {
            s32 groupOffset = index * sizeof(struct PartySkillInfo)
                + offsetof(struct PartySkillInfo, characterGroupBits);

            if (characterId == (*(const u8 *)(groupOffset + (u32)groups) >> 4)
                && gPartySkillTable[index].requiredLevel == level)
                return index + 1;
        }
    }
    return PARTY_NO_SKILL;
}

void Party_InitCharactersAndInventory(void)
{
    u8 index;

    for (index = 1; index <= PARTY_CHARACTER_COUNT; index++)
        Party_InitCharacter(index);
    for (index = 1; index < PARTY_ITEM_COUNT - 1; index++)
        gPartyItemCounts[index] = 0;
}

u8 Party_GetSkillMpCost(u8 skillId)
{
    const u8 *skills = (const u8 *)gPartySkillTable;
    s32 offset = (skillId - 1) * sizeof(struct PartySkillInfo)
        + offsetof(struct PartySkillInfo, mpCost);

    return skills[offset];
}

